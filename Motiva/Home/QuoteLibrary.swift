    /// Shipped topics only (`Unfiltered (NSFW)` stays in `allTopics` for archival, not in the app UI).
    static let topics: [QuoteTopic] = allTopics.filter { $0.name != "Unfiltered (NSFW)" }

    /// The mixed feed shown when no topic is selected: featured quotes first, then every topic interleaved.
    static let forYou: [String] = {
        var mixed = featured
        let longest = topics.map(\.quotes.count).max() ?? 0
        for index in 0..<longest {
            for topic in topics where topic.name != "Featured" && index < topic.quotes.count {
                mixed.append(topic.quotes[index])
            }
        }
        return mixed
    }()

    static func quotes(for topicName: String?, followedTopics: [String] = []) -> [String] {
        if let topicName {
            guard let topic = topics.first(where: { $0.name == topicName }) else { return forYou }
            return topic.quotes
        }
        if !followedTopics.isEmpty {
            return blended(following: followedTopics)
        }
        return forYou
    }

    /// Round-robin mix of the topics the user follows (For you when no single topic is selected).
    static func blended(following names: [String]) -> [String] {
        var orderedNames: [String] = []
        for name in names where !orderedNames.contains(name) {
            orderedNames.append(name)
        }

        var mixed: [String] = []
        if orderedNames.contains("Featured") {
            mixed.append(contentsOf: featured)
            orderedNames.removeAll { $0 == "Featured" }
        }

        let selected = topics.filter { orderedNames.contains($0.name) }
        guard !selected.isEmpty else { return mixed.isEmpty ? forYou : mixed }

        let longest = selected.map(\.quotes.count).max() ?? 0
        for index in 0..<longest {
            for topic in selected where index < topic.quotes.count {
                mixed.append(topic.quotes[index])
            }
        }
        return mixed.isEmpty ? forYou : mixed
    }
